"""Regenerates the bundled SYNTHETIC example: a 60-row invoice-number dataset and two sets of
*simulated* model outputs, one per prompt version.

Nothing here is real model output and no real invoice is involved. The invoice texts are templated
and the "models" are two stated stochastic behaviours (below), so the example has paired data with a
known, moderate difference to run the statistics on. It exists to exercise the comparison offline,
not to say anything about any real prompt or model.

    baseline  (prompts/extractor_v1.txt, the loose prompt): often wraps the answer in a sentence
              ("The invoice number is X"), which exact_match scores 0 and `contains` scores 1; takes a
              distractor number on the harder templates; says "No invoice number found." instead of
              the requested NONE.
    candidate (prompts/extractor_v2.txt, the strict prompt): almost always answers bare, still takes
              a distractor sometimes, answers NONE when there is no number.

The seed is fixed and the first draw is the one committed (no re-rolling for a nicer result).
`tests/test_example_data.py` regenerates the files and fails if the committed ones differ.

    python benchmarks/make_example_data.py          # rewrite data/example_*
    python benchmarks/make_example_data.py --check  # exit 1 if the committed files are stale
"""

from __future__ import annotations

import argparse
import json
import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
SEED = 2026
N_ROWS = 60

# (template, hard) -- hard templates carry a distractor number next to the real one.
TEMPLATES = [
    ("Invoice {n} dated {d}", False),
    ("Inv. No: {n}, Total: R{amt}", False),
    ("Tax invoice no. {n} issued {d} (VAT reg 4{vat})", True),
    ("Reference {ref} — Invoice {n}", True),
    ("Customer ref {ref}; invoice number {n}; due {d}", True),
]
NO_NUMBER_TEXTS = [
    "Statement of account, no invoice number on this page.",
    "Remittance advice for {d}: payment received, thank you.",
    "Delivery note {ref} (not an invoice).",
]

# P(outcome | prompt, hard). Remaining probability is the correct bare answer.
BASELINE = {"wrapped": 0.30, "distractor_easy": 0.04, "distractor_hard": 0.18}
CANDIDATE = {"wrapped": 0.04, "distractor_easy": 0.04, "distractor_hard": 0.14}
P_NONE_RIGHT = {"baseline": 0.15, "candidate": 0.85}  # answers exactly NONE when there is no number


def _invoice_no(rng: random.Random) -> str:
    style = rng.choice(["digits", "prefixed", "slashed"])
    if style == "digits":
        return str(rng.randint(10000, 99999))
    if style == "prefixed":
        return f"{rng.choice(['AB', 'INV', 'KT'])}-{rng.randint(1000, 9999)}"
    return f"INV/2025/{rng.randint(1, 999):04d}"


def _date(rng: random.Random) -> str:
    return f"2025-{rng.randint(1, 12):02d}-{rng.randint(1, 28):02d}"


def _answer(rng: random.Random, who: dict, number: str, ref: str, hard: bool) -> str:
    u = rng.random()
    p_dist = who["distractor_hard"] if hard else who["distractor_easy"]
    if u < p_dist:
        return ref
    if u < p_dist + who["wrapped"]:
        return f"The invoice number is {number}."
    return number


def generate() -> tuple[str, list[str], list[str]]:
    rng = random.Random(SEED)
    rows: list[tuple[str, str, bool]] = []  # (text, expected, hard)
    refs: list[str] = []
    for i in range(N_ROWS):
        ref = str(rng.randint(10000, 99999))
        if i % 6 == 5:  # one row in six has no invoice number
            text = rng.choice(NO_NUMBER_TEXTS).format(d=_date(rng), ref=ref)
            rows.append((text, "NONE", False))
        else:
            tmpl, hard = rng.choice(TEMPLATES)
            n = _invoice_no(rng)
            text = tmpl.format(n=n, d=_date(rng), amt=f"{rng.randint(1, 99)},{rng.randint(0, 999):03d}",
                               vat=rng.randint(100000000, 999999999), ref=ref)
            rows.append((text, n, hard))
        refs.append(ref)

    out_rng = {"baseline": random.Random(SEED + 1), "candidate": random.Random(SEED + 2)}
    outputs = {"baseline": [], "candidate": []}
    for (_, expected, hard), ref in zip(rows, refs, strict=True):
        for name, who in (("baseline", BASELINE), ("candidate", CANDIDATE)):
            r = out_rng[name]
            if expected == "NONE":
                outputs[name].append(
                    "NONE" if r.random() < P_NONE_RIGHT[name] else "No invoice number found."
                )
            else:
                outputs[name].append(_answer(r, who, expected, ref, hard))

    lines = [
        "# SYNTHETIC example dataset: 60 templated invoice texts. Not real invoices, not client data.",
        "# Generated by benchmarks/make_example_data.py; do not edit by hand.",
        "",
    ]
    for text, expected, _ in rows:
        lines += [f"- variables:\n    text: {json.dumps(text, ensure_ascii=False)}",
                  f"  expected: {json.dumps(expected, ensure_ascii=False)}", ""]
    return "\n".join(lines), outputs["baseline"], outputs["candidate"]


def files() -> dict[Path, str]:
    dataset, base, cand = generate()
    return {
        DATA / "example_dataset.yml": dataset,
        DATA / "example_outputs_baseline.json": json.dumps(base, indent=1, ensure_ascii=False) + "\n",
        DATA / "example_outputs_candidate.json": json.dumps(cand, indent=1, ensure_ascii=False) + "\n",
    }


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    stale = []
    for path, text in files().items():
        if args.check:
            if not path.exists() or path.read_bytes() != text.encode("utf-8"):
                stale.append(path.name)
        else:
            path.write_bytes(text.encode("utf-8"))  # bytes: LF on every platform
            print("wrote", path.relative_to(ROOT))
    if stale:
        print("stale:", ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
